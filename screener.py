# screener.py 하단의 run_screener 함수를 아래 코드로 교체하세요.


def run_screener(threshold_pct=2.0):
  name_map = get_all_stock_meta()
  tickers = sorted(list(name_map.keys()))
  print(f"총 {len(tickers)}개 전 종목 시세 및 거래량 다운로드 시작...")

  raw_data = yf.download(
      tickers, period="18mo", interval="1d", auto_adjust=True, progress=True
  )
  close_df = raw_data["Close"]
  vol_df = raw_data["Volume"]
  high_df = raw_data["High"]

  screened_results = {"20": [], "200": []}
  windows = {"20": 20, "200": 200}

  for ticker in tickers:
    try:
      if ticker not in close_df.columns:
        continue
      series = close_df[ticker].dropna()
      if len(series) < 200:
        continue

      current_price = float(series.iloc[-1])

      # 1. RSI(14) 계산
      rsi_series = calculate_rsi(series, period=14)
      current_rsi = (
          float(rsi_series.iloc[-1])
          if not pd.isna(rsi_series.iloc[-1])
          else 50.0
      )
      rsi_status = "과매도" if current_rsi <= 30 else "일반"

      # 2. 20일 평균 대비 거래량 비율(%) 계산
      vol_ratio = 100.0
      if ticker in vol_df.columns:
        v_series = vol_df[ticker].dropna()
        if len(v_series) >= 20:
          avg_vol20 = float(v_series.rolling(window=20).mean().iloc[-1])
          cur_vol = float(v_series.iloc[-1])
          if avg_vol20 > 0:
            vol_ratio = (cur_vol / avg_vol20) * 100

      # 3. 52주(252거래일) 최고가 대비 낙폭(%) 계산
      drop_52w = 0.0
      if ticker in high_df.columns:
        h_series = high_df[ticker].dropna().tail(252)
        if not h_series.empty:
          high_52w = float(h_series.max())
          if high_52w > 0:
            drop_52w = ((current_price - high_52w) / high_52w) * 100

      company_name = name_map.get(ticker, ticker)
      logo_url = f"https://financialmodelingprep.com/image-stock/{ticker}.png"

      for key, window in windows.items():
        sma_val = float(series.rolling(window=window).mean().iloc[-1])
        diff_pct = ((current_price - sma_val) / sma_val) * 100

        if abs(diff_pct) <= threshold_pct:
          trend_status = "지지" if diff_pct >= 0 else "저항"

          screened_results[key].append({
              "logo": logo_url,
              "ticker": ticker,
              "company_name": company_name,
              "current_price": round(current_price, 2),
              "sma": round(sma_val, 2),
              "diff_pct": round(diff_pct, 2),
              "trend_status": trend_status,
              "rsi": round(current_rsi, 1),
              "rsi_status": rsi_status,
              "vol_ratio": round(vol_ratio, 0),
              "drop_52w": round(drop_52w, 1),
          })
    except Exception:
      continue

  for key in screened_results:
    screened_results[key] = sorted(
        screened_results[key], key=lambda x: abs(x["diff_pct"])
    )

  payload = {
      "updated_at": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
      "total_screened": len(tickers),
      "results": screened_results,
  }

  with open("screened_stocks.json", "w", encoding="utf-8") as f:
    json.dump(payload, f, ensure_ascii=False, indent=2)

  print(
      f"스크리닝 완료! 총 {len(tickers)}개 중 20일선:"
      f" {len(screened_results['20'])}개, 200일선:"
      f" {len(screened_results['200'])}개"
  )


if __name__ == "__main__":
  run_screener(threshold_pct=2.0)